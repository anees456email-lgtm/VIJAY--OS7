def recon_report(**data):
    print("\033[1;3;35m Recon Report Starting...\033[0m")
    time.sleep(1)
    print(f"\033[1;93m Type Data: {type(data)}\033[0m")
    time.sleep(1)
    print("\033[1;96m" + "—" *50 + "\033[0m")
    time.sleep(1)
    for key,value in data.items():
        print(f"\033[1;3;32m {key} --> {value}\033[0m")
        time.sleep(1)
    target_ip = data.get("ip")
    if target_ip is None:
        print(f"\033[1;3;31m Alert! ip: Missing \033[0m")
        time.sleep(1)
    target_port = data.get("port")
    if target_port is None:
        print(f"\033[1;3;31m Alert! port Missing\033[0m")
        time.sleep(1)
    target_os = data.get("os")
    print(f"\033[1;3;31m os: {target_os}\033[0m")
    time.sleep(1)
    print("\033[1;96m" + "—" *50 + "\033[0m")
    time.sleep(1)
