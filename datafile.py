def scan_system(**target):
    print("\033[1;3;33m[+] Scan System Starting...\033[0m")
    time.sleep(1)
    for key,value in target.items():
        print(f"\033[1;3;31m>>> Key: {key}\033[0m")
        time.sleep(1)
        print(f"\033[1;3;32m--> Value: {value}\033[0m")
        time.sleep(1)
        print("\033[1;96m" + "—" *50 + "\033[0m")
        time.sleep(1)
    total_entries = len(target)
    print(f"\033[1;3;34m Total Entries: {total_entries} \033[0m")
    time.sleep(1)
